/******************************************************************************
 * PawnPro FB5 migration: Receive Stock -- supplier (wholesale) purchases (schema v15)
 *
 * Stock bought from a wholesaler or supplier is received against a supplier
 * invoice and goes straight to For Sale:
 *   SUPPLIERS             the suppliers, maintained once and picked per
 *                         receipt. Never deleted: ACTIVE = false hides an old one.
 *   STOCK_RECEIPTS        one row per supplier invoice: who, when, invoice no. and
 *                         total, payment type, notes. Voided receipts are kept
 *                         (RECEIPT_STATUS 'V').
 *   STOCK_RECEIPT_LINES   one row per item received, with the description, cost and
 *                         asking price as they were on the day. COPY_GROUP numbers
 *                         the pieces added together with "Copies" (1, 2, 3... within
 *                         the receipt; NULL for a single piece).
 *
 * Received items are ordinary INVENTORY_ITEMS rows: INV_ITEM_STATUS 'S',
 * PURCHASE_DATE and FORSALE_DATE = the receiving date, INV_ITEM_COUNT 1 (one row
 * per piece), and TRANSACTION_NO NULL. They are never in TRANSACTIONS, so they
 * can never reach a LeadsOnline export (every export finds items through
 * TRANSACTIONS) or a pawn / purchase list: a dealer purchase is not a reportable
 * transaction.
 *
 * Linked through STOCK_RECEIPT_LINES, not a new column on INVENTORY_ITEMS: this
 * migration changes nothing on that table (the busiest one, never altered by a
 * startup migration), so it cannot run into store workstations using it. There
 * is no FK from STOCK_RECEIPT_LINES to INVENTORY_ITEMS, for the same reason and
 * as with SALE_LINES (v12): a received item can be deleted (and logged, v14);
 * its receipt line stays, as the record of what came in.
 *
 * The v14 deleted-items log learns which receipt a deleted item came from:
 * INVENTORY_ITEMS_DELETED.STOCK_RECEIPT_NO, filled by TRG_INV_ITEMS_DELETED_LOG.
 *
 * Idempotent: tables, column and indexes are created only if missing, the
 * trigger with CREATE OR ALTER. Mirror of Step15_StockReceipts in uDBMigrations.pas.
 ******************************************************************************/

SET TERM ^ ;

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATIONS
                  WHERE RDB$RELATION_NAME = 'SUPPLIERS')) THEN
    EXECUTE STATEMENT
      'CREATE TABLE SUPPLIERS
       (
         SUPPLIER_NO         INTEGER        GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
         SUPPLIER_NAME       VARCHAR(80)    NOT NULL,
         CONTACT_NAME        VARCHAR(60),
         PHONE               VARCHAR(20),
         EMAIL               VARCHAR(80),
         ADDRESS             VARCHAR(120),
         CITY_ST_ZIP         VARCHAR(80),
         NOTES               VARCHAR(500),
         ACTIVE              BOOLEAN        DEFAULT TRUE NOT NULL,
         CREATED             TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
         CONSTRAINT PK_SUPPLIERS PRIMARY KEY (SUPPLIER_NO),
         CONSTRAINT UQ_SUPPLIERS_NAME UNIQUE (SUPPLIER_NAME)
       )';

  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATIONS
                  WHERE RDB$RELATION_NAME = 'STOCK_RECEIPTS')) THEN
    EXECUTE STATEMENT
      'CREATE TABLE STOCK_RECEIPTS
       (
         STOCK_RECEIPT_NO    INTEGER        GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
         SUPPLIER_NO         INTEGER        NOT NULL,
         RECEIVED_DATE       DATE           DEFAULT CURRENT_DATE NOT NULL,
         INVOICE_NO          VARCHAR(40),
         INVOICE_DATE        DATE,
         INVOICE_TOTAL       DECIMAL(18,2),
         PAY_TYPE_NO         INTEGER,
         NOTES               VARCHAR(500),
         RECEIPT_STATUS      CHAR(1)        DEFAULT ''A'' NOT NULL,
         VOID_DATE           TIMESTAMP,
         VOID_REASON         VARCHAR(120),
         CREATED             TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
         CONSTRAINT PK_STOCK_RECEIPTS PRIMARY KEY (STOCK_RECEIPT_NO),
         CONSTRAINT FK_STOCK_RECEIPTS_SUPPLIERS FOREIGN KEY (SUPPLIER_NO) REFERENCES SUPPLIERS (SUPPLIER_NO)
       )';

  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATIONS
                  WHERE RDB$RELATION_NAME = 'STOCK_RECEIPT_LINES')) THEN
    EXECUTE STATEMENT
      'CREATE TABLE STOCK_RECEIPT_LINES
       (
         STOCK_RECEIPT_LINE_NO INTEGER      GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
         STOCK_RECEIPT_NO    INTEGER        NOT NULL,
         INV_ITEM_NO         INTEGER        NOT NULL,
         DESCRIPTION         VARCHAR(120),
         UNIT_COST           DECIMAL(18,2),
         UNIT_PRICE          DECIMAL(18,2),
         COPY_GROUP          INTEGER,
         CONSTRAINT PK_STOCK_RECEIPT_LINES PRIMARY KEY (STOCK_RECEIPT_LINE_NO),
         CONSTRAINT FK_STOCK_RECEIPT_LINES_RECEIPTS FOREIGN KEY (STOCK_RECEIPT_NO) REFERENCES STOCK_RECEIPTS (STOCK_RECEIPT_NO)
       )';

  /* Pieces added together with "Copies" share a group number within their
     receipt (NULL for a single piece), so one edit can fix them all. Added
     after the first v15 build: guarded for a DB that already has the table. */
  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATION_FIELDS
                  WHERE RDB$RELATION_NAME = 'STOCK_RECEIPT_LINES'
                    AND RDB$FIELD_NAME = 'COPY_GROUP')) THEN
    EXECUTE STATEMENT 'ALTER TABLE STOCK_RECEIPT_LINES ADD COPY_GROUP INTEGER';

  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATION_FIELDS
                  WHERE RDB$RELATION_NAME = 'INVENTORY_ITEMS_DELETED'
                    AND RDB$FIELD_NAME = 'STOCK_RECEIPT_NO')) THEN
    EXECUTE STATEMENT 'ALTER TABLE INVENTORY_ITEMS_DELETED ADD STOCK_RECEIPT_NO INTEGER';
END^

SET TERM ; ^

COMMIT;

/* Receipts by date; "which receipt did this item come from?". */
SET TERM ^ ;
EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS (SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'STOCK_RECEIPTS_IDX1')) THEN
    EXECUTE STATEMENT 'CREATE ASC INDEX STOCK_RECEIPTS_IDX1 ON STOCK_RECEIPTS (RECEIVED_DATE)';
  IF (NOT EXISTS (SELECT 1 FROM RDB$INDICES WHERE RDB$INDEX_NAME = 'STOCK_RECEIPT_LINES_IDX1')) THEN
    EXECUTE STATEMENT 'CREATE ASC INDEX STOCK_RECEIPT_LINES_IDX1 ON STOCK_RECEIPT_LINES (INV_ITEM_NO)';
END^
SET TERM ; ^

COMMIT;

/* The v14 deleted-items trigger, now also recording the stock receipt. Same as
   v14 otherwise. */
SET TERM ^ ;

CREATE OR ALTER TRIGGER TRG_INV_ITEMS_DELETED_LOG FOR INVENTORY_ITEMS
ACTIVE BEFORE DELETE POSITION 0 SQL SECURITY INVOKER AS
DECLARE VARIABLE TICKET VARCHAR(30);
DECLARE VARIABLE TTYPE CHAR(1);
DECLARE VARIABLE DEL_WITH CHAR(1) = 'I';
BEGIN
  SELECT TRAN_TICKET_NO, TRAN_TYPE FROM TRANSACTIONS
   WHERE TRANSACTION_NO = OLD.TRANSACTION_NO
    INTO :TICKET, :TTYPE;

  /* Deleted with its transaction: that row is already gone, so take the
     ticket the transaction trigger left behind. */
  IF (RDB$GET_CONTEXT('USER_TRANSACTION', 'PAWNPRO_DEL_TRAN_NO') = CAST(OLD.TRANSACTION_NO AS VARCHAR(20))) THEN
  BEGIN
    DEL_WITH = 'T';
    TICKET = COALESCE(TICKET, RDB$GET_CONTEXT('USER_TRANSACTION', 'PAWNPRO_DEL_TRAN_TICKET'));
    TTYPE = COALESCE(TTYPE, RDB$GET_CONTEXT('USER_TRANSACTION', 'PAWNPRO_DEL_TRAN_TYPE'));
  END

  INSERT INTO INVENTORY_ITEMS_DELETED (
    INV_ITEM_NO, INV_ITEM_BARCODE, INV_CAT_NO, J_TYPE, J_STYLE, J_METAL, GENDER,
    INV_ITEM_COUNT, DESCRIPTION, NOTE, INV_ITEM_BRAND, MODEL_NUMBER, SERIAL_NUMBER,
    OWNER_APP_NUMBER, SIZE_LENGTH, WEIGHT, WEIGHT_UNIT, KT, UNIT_COST, UNIT_PRICE,
    INV_ITEM_STATUS, TRANSACTION_NO, TRAN_TICKET_NO, TRAN_TYPE, INV_ORIGINAL_ITEM_NO,
    CREATED, PAWNED_DATE, PURCHASE_DATE, REDEEMED_DATE, DEFAULTED_DATE, MELTED_DATE,
    FORSALE_DATE, SOLD_DATE, LAYAWAY_DATE,
    STONES, SALE_TICKETS, STOCK_RECEIPT_NO, DELETED_WITH, DELETED_ON, DELETE_REASON)
  VALUES (
    OLD.INV_ITEM_NO, OLD.INV_ITEM_BARCODE, OLD.INV_CAT_NO, OLD.J_TYPE, OLD.J_STYLE, OLD.J_METAL, OLD.GENDER,
    OLD.INV_ITEM_COUNT, OLD.DESCRIPTION, OLD.NOTE, OLD.INV_ITEM_BRAND, OLD.MODEL_NUMBER, OLD.SERIAL_NUMBER,
    OLD.OWNER_APP_NUMBER, OLD.SIZE_LENGTH, OLD.WEIGHT, OLD.WEIGHT_UNIT, OLD.KT, OLD.UNIT_COST, OLD.UNIT_PRICE,
    OLD.INV_ITEM_STATUS, OLD.TRANSACTION_NO, :TICKET, :TTYPE, OLD.INV_ORIGINAL_ITEM_NO,
    OLD.CREATED, OLD.PAWNED_DATE, OLD.PURCHASE_DATE, OLD.REDEEMED_DATE, OLD.DEFAULTED_DATE, OLD.MELTED_DATE,
    OLD.FORSALE_DATE, OLD.SOLD_DATE, OLD.LAYAWAY_DATE,
    (SELECT CAST(LEFT(LIST(s.STONE_NUMBER || 'x ' || TRIM(COALESCE(s.STONE_TYPE, '') || ' ' ||
                                 s.STONE_SHAPE || '/' || s.STONE_COLOR) ||
                           COALESCE(' ' || CAST(s.CT AS DECIMAL(9,3)) || 'ct', ''), '; '), 1000) AS VARCHAR(1000))
       FROM STONES s WHERE s.INV_ITEM_NO = OLD.INV_ITEM_NO),
    (SELECT CAST(LEFT(LIST(sa.SALE_TICKET_NO ||
                           IIF(sa.SALE_STATUS = 'V', ' (voided)', ''), ', '), 500) AS VARCHAR(500))
       FROM SALE_LINES l JOIN SALES sa ON sa.SALE_NO = l.SALE_NO
      WHERE l.INV_ITEM_NO = OLD.INV_ITEM_NO),
    (SELECT FIRST 1 rl.STOCK_RECEIPT_NO FROM STOCK_RECEIPT_LINES rl
      WHERE rl.INV_ITEM_NO = OLD.INV_ITEM_NO),
    :DEL_WITH,
    LEFT(COALESCE(RDB$GET_CONTEXT('SYSTEM', 'CLIENT_HOST'),
                  RDB$GET_CONTEXT('SYSTEM', 'CLIENT_ADDRESS'), CURRENT_USER), 255),
    LEFT(RDB$GET_CONTEXT('USER_TRANSACTION', 'PAWNPRO_DELETE_REASON'), 200));
END^

SET TERM ; ^

COMMIT;
