/******************************************************************************
 * PawnPro FB5 migration: log of deleted items and transactions (schema v14)
 *
 * Deleting an item or a transaction now leaves a record behind:
 *   INVENTORY_ITEMS_DELETED   a copy of each deleted item as it was, with its
 *                             stones and sale tickets as text, its pawn /
 *                             purchase ticket, and who / when / why.
 *   TRANSACTIONS_DELETED      a copy of each deleted transaction, with the
 *                             customer's name and its item and payment counts.
 *
 * Filled by BEFORE DELETE triggers, not by the screens. That catches every
 * path, including deleting a whole transaction, which removes its items and
 * payments through the ON DELETE CASCADE foreign keys. BEFORE, not AFTER, so
 * the item's stones and the transaction's items and payments still exist when
 * the copy is taken.
 *
 * Who / why. The app has no user login and every PC connects as the same
 * database user, so "who" is the PC: CLIENT_HOST (or CLIENT_ADDRESS) from
 * RDB$GET_CONTEXT('SYSTEM', ...). The reason is typed in the app, which puts it
 * in RDB$SET_CONTEXT('USER_TRANSACTION', 'PAWNPRO_DELETE_REASON', ...) inside
 * the same transaction as the delete (TDM.DeleteWithLog). It is required only
 * when sold items are deleted.
 *
 * DELETED_WITH: 'I' = the item was deleted on its own, 'T' = it went with its
 * transaction. The transaction trigger leaves PAWNPRO_DEL_TRAN_NO / _TICKET /
 * _TYPE in the transaction context, so its items' copies keep the ticket even
 * though the TRANSACTIONS row is already gone when the cascade reaches them.
 *
 * Idempotent: tables are created only if missing, triggers with CREATE OR ALTER.
 * Mirror of Step14_DeletedRecordsLog in uDBMigrations.pas.
 ******************************************************************************/

