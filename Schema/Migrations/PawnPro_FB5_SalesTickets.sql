/*******************************************************************************
 * PawnPro — Firebird 5 migration: SALES / SALE_LINES (sale tickets)
 *
 * Until now selling an item only flipped it to Sold ('D' + SOLD_DATE); nothing
 * recorded the sale as a whole. A sale is now a numbered ticket:
 *
 *   SALES       one row per ticket. The money is stored as it was on the day
 *               (subtotal, whole-sale discount, tax rate and amount, total) so
 *               a later Store Settings change never rewrites an old ticket.
 *               A voided ticket stays here with SALE_STATUS = 'V' -- tickets
 *               are never deleted.
 *   SALE_LINES  one row per item on the ticket: quantity, cost and asking
 *               price at the time, the sale price typed, its share of the
 *               whole-sale discount and the net price.
 *
 * SALE_TICKET_NO comes from TABLE_KEYS 'SaleTicketNo' (like pawn and layaway
 * tickets), bumped inside the sale's own transaction so a failed sale never
 * uses up a number. Each sale adds a random 1..9, starting after 3999, so the
 * gap between two receipts does not show how many sales happened in between;
 * numbers still increase. Gaps are deliberate; SALE_NO keeps creation order.
 *
 * Not a TRANSACTIONS row with a new TRAN_TYPE: the LeadsOnline export, the pawn
 * lists and Report02 all read TRANSACTIONS, and a missed filter would send
 * retail sales to the police or into the pawn totals.
 *
 * The legacy SALES_ITEMS table (ASA era, no header, never used by the FB app)
 * is unrelated and left alone.
 *
 * No FK from SALE_LINES to INVENTORY_ITEMS: creating one needs INVENTORY_ITEMS
 * free of other attachments, and the migration runs at startup while store
 * workstations may be connected. The app refuses to delete a transaction whose
 * items are on a sale ticket instead (TDM.GetSaleTicketsOfTransaction).
 *
 * CUST_NO is for later (sales to a known customer); PAY_TYPE_NO is always 1
 * (Cash, PAYMENT_TYPES) until card payments come.
 *
 * Idempotent: safe to re-run.
 ******************************************************************************/

SET TERM ^ ;

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATIONS
                  WHERE RDB$RELATION_NAME = 'SALES')) THEN
    EXECUTE STATEMENT
      'CREATE TABLE SALES
       (
         SALE_NO          INTEGER        GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
         SALE_TICKET_NO   INTEGER        NOT NULL,
         SALE_DATE        DATE           DEFAULT CURRENT_DATE NOT NULL,
         CUST_NO          INTEGER,
         SUBTOTAL         DECIMAL(18,2)  NOT NULL,
         DISCOUNT_TYPE    CHAR(1),
         DISCOUNT_VALUE   DECIMAL(18,2),
         DISCOUNT_AMOUNT  DECIMAL(18,2)  DEFAULT 0 NOT NULL,
         TAX_PERC         DECIMAL(9,4)   DEFAULT 0 NOT NULL,
         TAX_AMOUNT       DECIMAL(18,2)  DEFAULT 0 NOT NULL,
         TOTAL            DECIMAL(18,2)  NOT NULL,
         PAY_TYPE_NO      INTEGER        DEFAULT 1,
         SALE_STATUS      CHAR(1)        DEFAULT ''C'' NOT NULL,
         VOID_DATE        TIMESTAMP,
         VOID_REASON      VARCHAR(120),
         CREATED          TIMESTAMP      DEFAULT CURRENT_TIMESTAMP,
         CONSTRAINT PK_SALES PRIMARY KEY (SALE_NO),
         CONSTRAINT UQ_SALES_TICKET_NO UNIQUE (SALE_TICKET_NO)
       )';

  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATIONS
                  WHERE RDB$RELATION_NAME = 'SALE_LINES')) THEN
    EXECUTE STATEMENT
      'CREATE TABLE SALE_LINES
       (
         SALE_LINE_NO     INTEGER        GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
         SALE_NO          INTEGER        NOT NULL,
         INV_ITEM_NO      INTEGER        NOT NULL,
         ITEM_COUNT       INTEGER,
         DESCRIPTION      VARCHAR(120),
         UNIT_COST        DECIMAL(18,2),
         LIST_PRICE       DECIMAL(18,2),
         SALE_PRICE       DECIMAL(18,2)  NOT NULL,
         DISCOUNT_SHARE   DECIMAL(18,2)  DEFAULT 0 NOT NULL,
         NET_PRICE        DECIMAL(18,2)  NOT NULL,
         CONSTRAINT PK_SALE_LINES PRIMARY KEY (SALE_LINE_NO),
         CONSTRAINT FK_SALE_LINES_SALES FOREIGN KEY (SALE_NO) REFERENCES SALES (SALE_NO)
       )';

  /* Indexes. SALE_LINES.INV_ITEM_NO has no FK (see above), so nothing else
     indexes it, and every "is this item on a ticket?" lookup goes by it.
     SALE_DATE is what the ticket history screen will list by. */
  IF (NOT EXISTS (SELECT 1 FROM RDB$INDICES
                  WHERE RDB$INDEX_NAME = 'SALE_LINES_IDX1')) THEN
    EXECUTE STATEMENT 'CREATE ASC INDEX SALE_LINES_IDX1 ON SALE_LINES (INV_ITEM_NO)';

  IF (NOT EXISTS (SELECT 1 FROM RDB$INDICES
                  WHERE RDB$INDEX_NAME = 'SALES_IDX1')) THEN
    EXECUTE STATEMENT 'CREATE ASC INDEX SALES_IDX1 ON SALES (SALE_DATE)';
END^

SET TERM ; ^

COMMIT;

/* Sale ticket counter, starting at 3999: the first ticket is 4000-4008, and
   each sale adds a random 1..9 (TDM.CompleteSale), so ticket numbers do not
   reveal the store's sales volume. */
INSERT INTO TABLE_KEYS (TABLE_NAME, LAST_KEY)
  SELECT 'SaleTicketNo', 3999 FROM RDB$DATABASE
   WHERE NOT EXISTS (SELECT 1 FROM TABLE_KEYS WHERE TABLE_NAME = 'SaleTicketNo');

COMMIT;
