/* ---------------------------------------------------------------------------
   LEADS_SOAP_NO_ACTIVITY -- days declared to LeadsOnline as having no pawns.

   The web service operation SetNoTransactionDayForStore tells law enforcement
   that a given day had no pawn activity, instead of leaving them to infer it
   from silence. Asked for by Gema Jewelers, whose local department wants to be
   told rather than assume.

   One row per date. Every attempt is recorded, successes and failures alike:
   the notification screen's grid exists to show what went wrong, and a table
   holding only successes could not do that. Written with UPDATE OR INSERT
   MATCHING (ACTIVITY_DATE) so a retry after a connection failure overwrites the
   earlier attempt rather than being blocked by the unique constraint.

   ERROR_CODE 0 means LeadsOnline accepted the declaration. A non-zero code
   means they reached a decision and refused: that one is finished here and has
   to be done on the LeadsOnline website.

   Idempotent. Safe to run against a database that already has it.
   --------------------------------------------------------------------------- */

SET TERM ^ ;

EXECUTE BLOCK AS
BEGIN
  IF (NOT EXISTS (SELECT 1 FROM RDB$RELATIONS
                   WHERE RDB$RELATION_NAME = 'LEADS_SOAP_NO_ACTIVITY')) THEN
    EXECUTE STATEMENT
      'CREATE TABLE LEADS_SOAP_NO_ACTIVITY
       (
         ID              INTEGER   GENERATED BY DEFAULT AS IDENTITY (START WITH 1) NOT NULL,
         ACTIVITY_DATE   DATE      NOT NULL,
         DECLARED_AT     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
         ERROR_CODE      INTEGER,
         ERROR_RESPONSE  VARCHAR(500),
         CONSTRAINT PK_LEADS_SOAP_NO_ACTIVITY PRIMARY KEY (ID),
         CONSTRAINT UQ_LEADS_SOAP_NO_ACTIVITY UNIQUE (ACTIVITY_DATE)
       )';
END^

SET TERM ; ^
