 *   5. SPU_LANG_UPSERT natural-key upsert procedure
 *   6. SPD_LANG_DELETE natural-key delete procedure
 *   7. English and Spanish language seeds
 *
 * Important ownership rules:
 *   - Stored business codes are never translated.
 *   - Form/literal English and translations live in ML_LANG_VALUES.
 *   - Lookup English remains canonical in its base *_DESC column.
 *   - ML_LANG_VALUES stores only non-English overlays for lookup objects.
 *   - A missing translation is represented by no ML_LANG_VALUES row.
 *   - Empty/whitespace-only translation rows are rejected.
